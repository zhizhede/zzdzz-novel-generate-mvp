CREATE TABLE derive_beat_pool (
    id BIGSERIAL PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES run(id) ON DELETE CASCADE,
    beat_key TEXT NOT NULL,
    pool_seq INTEGER NOT NULL,
    beat_role TEXT NOT NULL,
    source TEXT NOT NULL,
    goal TEXT NOT NULL,
    novelty TEXT NOT NULL,
    state_before JSONB NOT NULL DEFAULT '[]'::jsonb,
    state_after JSONB NOT NULL DEFAULT '[]'::jsonb,
    depends_on JSONB NOT NULL DEFAULT '[]'::jsonb,
    focus_characters JSONB NOT NULL DEFAULT '[]'::jsonb,
    thread_refs JSONB NOT NULL DEFAULT '[]'::jsonb,
    requires_knowledge JSONB NOT NULL DEFAULT '[]'::jsonb,
    writes_knowledge JSONB NOT NULL DEFAULT '[]'::jsonb,
    reveal_level SMALLINT NOT NULL DEFAULT 0,
    required BOOLEAN NOT NULL DEFAULT FALSE,
    protected BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'PLANNED',
    contract JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_user_id BIGINT,
    updated_user_id BIGINT,
    UNIQUE(run_id, beat_key),
    UNIQUE(run_id, pool_seq)
);
CREATE INDEX idx_derive_beat_pool_run ON derive_beat_pool(run_id, pool_seq);
