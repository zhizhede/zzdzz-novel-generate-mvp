-- 卷级规划：每卷独立事件、卷末闭合与下一卷钩子。
CREATE TABLE IF NOT EXISTS derive_volume_plan (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT NOT NULL REFERENCES run(id),
    novel_id        BIGINT NOT NULL REFERENCES novels(id),
    volume_no       INT NOT NULL,
    from_chapter    INT NOT NULL,
    to_chapter      INT NOT NULL,
    arc             VARCHAR(128) NOT NULL,
    local_event     TEXT NOT NULL,
    local_closure   TEXT NOT NULL,
    next_hook       TEXT NOT NULL DEFAULT '',
    global_role     VARCHAR(16) NOT NULL DEFAULT 'LOCAL',
    status          VARCHAR(16) NOT NULL DEFAULT 'PLANNED',
    created_time    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_time    TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_user_id BIGINT,
    updated_user_id BIGINT
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_derive_volume_plan_no
    ON derive_volume_plan(run_id, volume_no);

ALTER TABLE chapters ADD COLUMN IF NOT EXISTS volume_no INT;
ALTER TABLE beat_instance ADD COLUMN IF NOT EXISTS volume_no INT;

CREATE INDEX IF NOT EXISTS idx_chapters_volume
    ON chapters(novel_id, volume_no);
CREATE INDEX IF NOT EXISTS idx_beat_instance_volume
    ON beat_instance(run_id, volume_no);
