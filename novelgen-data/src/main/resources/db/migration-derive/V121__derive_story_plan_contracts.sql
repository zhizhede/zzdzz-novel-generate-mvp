-- V121: 故事脊柱、卷合同、角色弧光、线程账与语义拍路由合同。
-- world_states 仍是实时状态唯一事实源；本迁移不新增角色状态表。

CREATE TABLE derive_character_plan (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               BIGINT NOT NULL REFERENCES run(id) ON DELETE CASCADE,
    novel_id             BIGINT NOT NULL REFERENCES novels(id) ON DELETE CASCADE,
    character_key        VARCHAR(16) NOT NULL,
    display_name_hint    VARCHAR(64),
    function_code        VARCHAR(32) NOT NULL,
    spotlight_volume     INT,
    conflict_volume      INT,
    payoff_volume        INT,
    arc_before           TEXT NOT NULL DEFAULT '',
    arc_after            TEXT NOT NULL DEFAULT '',
    contract             JSONB NOT NULL DEFAULT '{}',
    status               VARCHAR(16) NOT NULL DEFAULT 'PLANNED',
    created_time         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_time         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_user_id      BIGINT,
    updated_user_id      BIGINT,
    CONSTRAINT uq_derive_character_plan UNIQUE (run_id, character_key)
);

CREATE INDEX idx_derive_character_plan_run
    ON derive_character_plan(run_id, spotlight_volume);

COMMENT ON TABLE derive_character_plan IS
    '角色叙事计划：功能、高光、冲突、弧光前后；实时状态仍以 world_states 为准';

CREATE TABLE derive_story_thread (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               BIGINT NOT NULL REFERENCES run(id) ON DELETE CASCADE,
    novel_id             BIGINT NOT NULL REFERENCES novels(id) ON DELETE CASCADE,
    thread_key           VARCHAR(32) NOT NULL,
    kind                 VARCHAR(16) NOT NULL,
    title                VARCHAR(128) NOT NULL,
    opened_volume        INT,
    payoff_volume        INT,
    owner_character_key  VARCHAR(16),
    status               VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    contract             JSONB NOT NULL DEFAULT '{}',
    created_time         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_time         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_user_id      BIGINT,
    updated_user_id      BIGINT,
    CONSTRAINT ck_derive_story_thread_kind
        CHECK (kind IN ('CLUE', 'RELATIONSHIP', 'OBJECT')),
    CONSTRAINT ck_derive_story_thread_status
        CHECK (status IN ('OPEN', 'ECHOED', 'CONFIRMED', 'PAYOFF', 'CLOSED')),
    CONSTRAINT uq_derive_story_thread UNIQUE (run_id, thread_key)
);

CREATE INDEX idx_derive_story_thread_run
    ON derive_story_thread(run_id, kind, payoff_volume);

COMMENT ON TABLE derive_story_thread IS
    '线索、关系与物件线程账：生命周期、埋设/兑现章节和参与角色';

ALTER TABLE derive_volume_plan
